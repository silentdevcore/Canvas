export function accountLocale(): AccountLocale {
  const stored = localStorage.getItem('pxa_locale')?.split('-')[0];
  const browser = navigator.language?.split('-')[0];
  const locale = stored || browser || 'en';
  return accountLocales.includes(locale as AccountLocale) ? locale as AccountLocale : 'en';
}

export function setAccountLocale(locale: string): void {
  if (accountLocales.includes(locale as AccountLocale))
    localStorage.setItem('pxa_locale', locale);
}

export function tr(key: TranslationKey): string {
  const locale = accountLocale();
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  return translations[locale][key];
}
