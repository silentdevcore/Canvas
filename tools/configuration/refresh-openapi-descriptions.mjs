import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const ts = createRequire(new URL('../../pvad-designer/package.json', import.meta.url))('typescript');

export function refreshDescriptions(document, descriptions) {
  if (!Array.isArray(descriptions) || descriptions.length !== 16) throw new Error('Expected sixteen transformer descriptions.');
  const result = structuredClone(document), seen = new Set();
  for (const entry of descriptions) {
    if (!/^\/api\/pvad\/v1\/(?:designer\/projects|pdf\/e-invoices)\//.test(entry.path)
      || entry.method !== 'post' || typeof entry.description !== 'string' || /pxa/i.test(entry.description)
      || seen.has(entry.path)) throw new Error('Invalid or duplicate description projection.');
    seen.add(entry.path);
    const operation = result.paths?.[entry.path]?.post;
    if (!operation || (operation.operationId ?? null) !== entry.operationId)
      throw new Error('The transformer projection may not change operation identities.');
    operation.description = entry.description;
  }
  return result;
}

export function rewriteDescriptionSource(source, descriptions) {
  const document = refreshDescriptions(JSON.parse(source), descriptions);
  const tree = ts.parseJsonText('openapi.json', source), edits = [];
  function visit(node, path) {
    if (ts.isObjectLiteralExpression(node))
      for (const property of node.properties) visit(property.initializer, [...path, property.name.text]);
    else if (path.length === 4 && path[0] === 'paths' && path[2] === 'post' && path[3] === 'description'
      && ts.isStringLiteral(node)) {
      const next = document.paths[path[1]].post.description;
      if (next !== node.text) edits.push({ start: node.getStart(tree), end: node.end, value: JSON.stringify(next) });
    }
  }
  tree.statements.forEach(statement => visit(statement.expression, []));
  for (const edit of edits.sort((a, b) => b.start - a.start))
    source = source.slice(0, edit.start) + edit.value + source.slice(edit.end);
  return source;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.length !== 3) throw new Error('Provide the transformer projection generated by OpenApiNamingSnapshotTests.');
  const file = fileURLToPath(new URL('../../docs/schema/openapi.json', import.meta.url));
  const source = readFileSync(file, 'utf8');
  const descriptions = JSON.parse(readFileSync(resolve(process.argv[2])));
  writeFileSync(file, rewriteDescriptionSource(source, descriptions));
  console.log('Refreshed sixteen documentation descriptions without changing API contracts.');
}
