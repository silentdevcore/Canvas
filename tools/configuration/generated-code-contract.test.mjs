import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const root = fileURLToPath(new URL('../..', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8');
const files = directory => readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
  if (['bin', 'obj', 'node_modules', '.git'].includes(entry.name)) return [];
  const path = resolve(directory, entry.name);
  return entry.isDirectory() ? files(path) : entry.name.endsWith('.cs') ? [path] : [];
});

test('owned C# declarations and imports use PVAD without rewriting diagnostic or document text', () => {
  const legacy = [...files(resolve(root, 'src')), ...files(resolve(root, 'PVAD.WebApi'))]
    .filter(path => /\b(?:using|namespace)\s+(?:PXA|Canvas)(?:\.|\s*;)/.test(readFileSync(path, 'utf8')));
  assert.deepEqual(legacy, []);
});

test('worker scaffolding and code generators reference renamed artifacts and identities', () => {
  const worker = read('src/Execution/PVAD.CodeWorker/Program.cs');
  assert.ok(worker.includes('"PVAD.Core.Contracts"'));
  assert.ok(worker.includes('"PVAD.Generator"'));
  assert.ok(worker.includes('"PVAD.Pdf"'));
  const client = read('PVAD.WebApi/Application/Designer/PvadCodeWorkerClient.cs');
  assert.ok(client.includes('"PVAD.CodeWorker.dll"'));
  assert.ok(client.includes('CreateTempSubdirectory("pvad-code-")'));
  const generator = read('PVAD.WebApi/Application/Designer/PvadCodeConversionService.cs');
  assert.equal((generator.match(/Generated by PVAD\./g) ?? []).length, 3);
  assert.equal(generator.includes('Generated by PXA.'), false);
  const project = read('PVAD.WebApi/PVAD.WebApi.csproj');
  assert.ok(project.includes('src/Execution/PVAD.CodeWorker/PVAD.CodeWorker.csproj'));
  assert.equal(project.includes('PXA.CodeWorker'), false);
});
